"""Freeze the tested environment with release hashes for all available platforms.

Run only after installing the .in files in an isolated Python 3.12 environment,
passing pip check and the test suite. This captures installed versions; it does
not resolve upgrades. pip-tools remains available for dependency upgrades.
"""
import json
import re
from concurrent.futures import ThreadPoolExecutor
from importlib.metadata import distribution
from pathlib import Path
from urllib.request import urlopen

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def inputs(path: Path) -> list[Requirement]:
    requirements = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-c ")):
            continue
        if line.startswith("-r "):
            requirements.extend(inputs(path.parent / line[3:].strip()))
        else:
            requirements.append(Requirement(line))
    return requirements


def collect(requirements: list[Requirement]) -> dict[str, str]:
    versions: dict[str, str] = {}
    visited = set()
    environments = []
    for system, platform, os_name in [("Linux", "linux", "posix"),
                                      ("Windows", "win32", "nt"), ("Darwin", "darwin", "posix")]:
        environment = default_environment()
        environment.update(platform_system=system, sys_platform=platform, os_name=os_name, extra="")
        environments.append(environment)
    pending = [(requirement, "") for requirement in requirements]
    while pending:
        requirement, parent_extra = pending.pop()
        if requirement.marker and not any(
            requirement.marker.evaluate(dict(environment, extra=parent_extra)) for environment in environments
        ):
            continue
        name = canonicalize_name(requirement.name)
        installed = distribution(name)
        if installed.version not in requirement.specifier:
            raise RuntimeError(f"Installed {name} does not satisfy {requirement.specifier}")
        versions[name] = installed.version
        for extra in {"", *requirement.extras}:
            if (name, extra) in visited:
                continue
            visited.add((name, extra))
            pending.extend((Requirement(value), extra) for value in installed.requires or [])
    return versions


def release_hashes(item: tuple[str, str]) -> tuple[str, list[str]]:
    name, version = item
    with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        release = json.load(response)
    hashes = sorted({file["digests"]["sha256"] for file in release["urls"]})
    if not hashes or not all(re.fullmatch(r"[a-f0-9]{64}", value) for value in hashes):
        raise RuntimeError(f"Missing valid distribution hashes for {name}")
    return name, hashes


def main() -> None:
    runtime = collect(inputs(ROOT / "requirements.in"))
    development = collect(inputs(ROOT / "requirements-dev.in"))
    with ThreadPoolExecutor(max_workers=8) as executor:
        hashes = dict(executor.map(release_hashes, development.items()))
    for filename, versions in [("requirements.txt", runtime), ("requirements-dev.txt", development)]:
        lines = ["# Exact versions from the tested Python 3.12 environment.",
                 "# Generated by scripts/lock_tested_environment.py; SHA256 from PyPI release metadata.",
                 "# Includes available Windows, Linux and macOS distribution hashes.", ""]
        for name, version in sorted(versions.items()):
            lines.append(f"{name}=={version} \\")
            digests = hashes[name]
            for index, digest in enumerate(digests):
                suffix = " \\" if index < len(digests) - 1 else ""
                lines.append(f"    --hash=sha256:{digest}{suffix}")
        (ROOT / filename).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Wrote {filename}: {len(versions)} pinned packages")


if __name__ == "__main__":
    main()
